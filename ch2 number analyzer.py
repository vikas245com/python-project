print("is_even = " , is_even)  
is_divisible_by_5 = num % 5 == 0 
print("is_divisible_by_5 =  " , is_divisible_by_5)
is_positive = num > 0
print("is_positive = " , is_positive) 
is_negative = num < 0
print("is_negative = " , is_negative) 
is_zero = num == 0 
print("is_zero = " , is_zero) 
square = num ** 2
print("square = " , square)
cube = num ** 3 
